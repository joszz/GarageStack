// Writes src/utils/timeZoneRegions.ts: every region's IANA time zones, from the CLDR data in
// Node's own ICU, so the browser can tell the region it is in from its time zone alone.
// Run with `node scripts/gen-time-zone-regions.mjs` after a Node upgrade brings a newer ICU.
import { writeFileSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'

const __dirname = dirname(fileURLToPath(import.meta.url))
const OUT = join(__dirname, '..', 'src', 'utils', 'timeZoneRegions.ts')

// CLDR keeps the old spelling of a renamed zone (Asia/Calcutta), which Chromium and Safari report,
// while Firefox reports the current IANA name (Asia/Kolkata). These are the current names, each
// checked below to be one of the zones ICU already knows.
const IANA_RENAMES = [
  'Africa/Asmara',
  'America/Argentina/Buenos_Aires',
  'America/Argentina/Catamarca',
  'America/Argentina/Cordoba',
  'America/Argentina/Jujuy',
  'America/Argentina/Mendoza',
  'America/Atikokan',
  'America/Indiana/Indianapolis',
  'America/Kentucky/Louisville',
  'America/Nuuk',
  'Asia/Ho_Chi_Minh',
  'Asia/Kathmandu',
  'Asia/Kolkata',
  'Asia/Yangon',
  'Atlantic/Faroe',
  'Europe/Kyiv',
  'Pacific/Chuuk',
  'Pacific/Kanton',
  'Pacific/Pohnpei',
]

const zonesByRegion = new Map()
const regionOfZone = new Map()
for (let a = 65; a <= 90; a++) {
  for (let b = 65; b <= 90; b++) {
    const region = String.fromCharCode(a, b)
    // A retired code (DD, SU, UK) canonicalizes to the one that replaced it, which lists the
    // same zones itself.
    if (Intl.getCanonicalLocales(`und-${region}`)[0] !== `und-${region}`) continue
    const zones = new Intl.Locale(`und-${region}`).getTimeZones?.() ?? []
    if (zones.length === 0) continue
    zonesByRegion.set(region, [...zones])
    for (const zone of zones) regionOfZone.set(zone, region)
  }
}

for (const name of IANA_RENAMES) {
  if (regionOfZone.has(name)) continue
  const known = new Intl.DateTimeFormat('en', { timeZone: name }).resolvedOptions().timeZone
  const region = regionOfZone.get(known)
  if (!region) throw new Error(`${name} resolves to ${known}, which no region lists`)
  zonesByRegion.get(region).push(name)
}

const lines = [...zonesByRegion]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([region, zones]) => `  ${region}: '${zones.sort().join(' ')}',`)

writeFileSync(
  OUT,
  `// Generated by scripts/gen-time-zone-regions.mjs from ICU ${process.versions.icu}. Do not edit by hand.

/** Each region's IANA time zones, space separated, under both spellings of a renamed zone. */
export const TIME_ZONE_REGIONS: Readonly<Record<string, string>> = {
${lines.join('\n')}
}
`,
)
console.log(`${zonesByRegion.size} regions written to ${OUT}`)
